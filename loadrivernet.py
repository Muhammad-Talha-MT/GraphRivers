def main():
    import argparse
    parser = argparse.ArgumentParser(
        formatter_class=argparse.RawDescriptionHelpFormatter,
        description="Parse arguments for genrivernet",
    )
    parser.add_argument('--config', type=str, required=True, help='config file name')
    cargs = parser.parse_args()
    
    args = load_config(cargs.config)
    watershed = args.watershed_name 
    comIDset,comIDdict,allDF,goodInd,gageDict = loadNWMDF(args)    

    
    formAdjacencyMat(args.rootdir, 
                     watershed=watershed,comIDdict=comIDdict,
                     goodIDSet=goodInd, 
                     plotting=args.network.plotadj,
                     isWeighting=args.network.weighted_adj,
                     nwm_ver=args.data.nwm_ver)
    
    #map gage comid to node index
    gageNodeInd=[]
    for item in gageDict.keys():
        try:
            #do reverse lookup
            gageNodeInd.append(comIDdict[item])
        except:
            pass
    print ('adj mat index of the observation nodes', gageNodeInd)
    
    #
    #=====Get USGS obs data (set reLoad to True if calling for first time) ===========
    #
    #for 3H data [this is not working for daymet]
    assert (args.data.interval in ['3H', '24H'])
    if args.data.interval=='3H':
        usgsDataDict = getUSGSData(watershed=watershed, gageIDset=gageDict.values(),
                       reLoad=args.data.reload_usgs, valueType='iv')
    else:
        #for 1d data
        usgsDataDict = getUSGSData(watershed=watershed, gageIDset=gageDict.values(),
                       reLoad=args.data.reload_usgs, valueType='dv')
    #this is the lookback period
    noffset = args.data.seq_length
    outputdir = os.path.join(args.rootdir, 'data/{0}'.format(watershed))

    #========Select different forcing data soruce =============
    if args.data.forcing_source in ['daymet', 'Daymet']:
        forcingDF = pkl.load(open('data/{0}/daymetforcing{1}_nwm{2}.pkl'.format(watershed, len(comIDset), args.data.nwm_ver),'rb'))
        in_dim = 7 #for daymet (6 forcing vars + Q), if removeSWE then in_dim will be reduced by 1 
        removeSWE = args.data.removeSWE
    elif args.data.forcing_source in ['nldas', 'NLDAS']:       
        forcingDF = pkl.load(open('data/{0}/nldasforcing{1}_nwm{2}_{3}.pkl'.format(watershed, len(comIDset), args.data.nwm_ver, args.data.interval),'rb'))
        in_dim = 6 #for nldas  (5 forcing vars + Q)
        removeSWE = False
    elif args.data.forcing_source in ['aorc', 'AORC']:
        forcingDF = pkl.load(open('data/{0}/aorcforcing{1}_nwm{2}_{3}.pkl'.format(watershed, len(comIDset), args.data.nwm_ver, args.data.interval),'rb'))
        in_dim = 3 #for aorc (2 forcing vars + Q)
        removeSWE = False
    elif args.data.forcing_source in ['era5', 'ERA5']:
        forcingDF = pkl.load(open('data/{0}/era5forcing_full_nwm{1}_{2}.pkl'.format(watershed, args.data.nwm_ver, args.data.interval),'rb'))
        in_dim = 9  # 8 ERA5 vars + Q
        removeSWE = False
    else:
        raise ValueError("Invalid forcing source ")
    
    #align allDF's date range to match the forcing data's actual coverage
    #(streamflow and forcing pickles were built from different source-year ranges,
    # so row i in allDF is not guaranteed to be the same date as row i in forcingDF)
    _sample_comid = next(iter(forcingDF.keys()))
    _forcing_start = forcingDF[_sample_comid].index.min()
    _forcing_end   = forcingDF[_sample_comid].index.max()
    print(f'forcing date range: {_forcing_start.date()} to {_forcing_end.date()}')
    print(f'allDF date range before align: {allDF.index.min().date()} to {allDF.index.max().date()} ({allDF.shape[0]} days)')
    allDF = allDF.loc[_forcing_start:_forcing_end]
    print(f'allDF date range after align:  {allDF.index.min().date()} to {allDF.index.max().date()} ({allDF.shape[0]} days)')
    for _c in comIDset:
        assert len(forcingDF[_c]) == allDF.shape[0], f'row count mismatch for comid {_c}: forcing={len(forcingDF[_c])} allDF={allDF.shape[0]}'

    #========Generate datasets ====================
    genMLDataSetsWithForcing(watershed,in_dim,comIDset,forcingDF,allDF,noffset,outputdir,
            trainRatio=(0.7,0.15),
            logTran=args.data.uselog,
            addStatics=args.data.addstatics,
            addNWM=args.data.addnwm,
            removeSWE= removeSWE,
            trainEndDate='2010-12-31',
            valEndDate='2015-12-31')


if __name__ == '__main__':
    main()