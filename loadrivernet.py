def formAdjacencyMat(rootDir,watershed,goodIDSet,comIDdict,isWeighting=False,isDirected=False, 
                     add_self_loop=False, plotting=False,connect_exta_path=False,watershedtype=1,
                     nwm_ver='2.0'):
    """Form adjacency mat using ONLY valid nodes
    Params
    ------
    rootDir,
    watershed, name of the watershed
    goodIDSet, id set of valid nodes
    """
    #hack to deal with different national water model version
    if nwm_ver=='2.0':
        adjfile = os.path.join(rootDir, 'data/{0}/adjinfo.pkl'.format(watershed))
    else:
        adjfile = os.path.join(rootDir, 'data/{0}/adjinfo{1}.pkl'.format(watershed,nwm_ver))
    #note the following info is on the whole node set. It's generated by genrivernet.py
    resDict = pkl.load(open(adjfile, 'rb'))
    num_nodes = resDict['num_nodes']
    startNode = resDict['start_node'] 
    endNode   = resDict['end_node']
    if watershedtype==1:
        #for fpp watershed, there's no edge length attr
        edgeLen   = resDict['edge_len']
    else:
        isWeighting=False
    if connect_exta_path:
        #Experimental feature, doesn't work well, so it's disabled by default
        print ('ADDING extra paths to adj mat ')
        for item in resDict['extra_path_nodes']:
            startNode.append(item[0])
            endNode.append(item[1])

    #!!!!Warning: this dense mat needs to be replaced by sparse mat for large arrays
    A = np.zeros((num_nodes,num_nodes))
    #
    #Constructed graph and add self loop (only if add self loop is true)
    #    
    if isWeighting:        
        imethod = 1
        #use the inverse distance as weight
        if imethod==1:
            #normalize edgeLen first
            edgeLen = 1.0/np.array(edgeLen)
            edgeLen = (edgeLen-np.min(edgeLen))/(np.max(edgeLen)-np.min(edgeLen))
            for i in range(len(startNode)):            
                A[startNode[i],endNode[i]] = edgeLen[i]
                if not isDirected:            
                    A[endNode[i],startNode[i]] = A[startNode[i],endNode[i]]               
        else:
            #this is Xiaowei's exp weighting method
            sigma2 = (np.std(edgeLen))**2 
            #edgeLen = edgeLen(np.nanmax(edgeLen))
            for i in range(len(startNode)):            
                dij = np.exp(-0.5*edgeLen[i]*edgeLen[i]/sigma2)
                A[startNode[i],endNode[i]] = dij #if dij>=0.5 else 0
                if not isDirected:
                    A[endNode[i],startNode[i]] = A[startNode[i],endNode[i]]        
            print ('sigma2',sigma2, np.nanmax(A))
    else:
        #unweighted undirected river distances
        for i in range(len(startNode)):
            A[startNode[i],endNode[i]] = 1.0
            if not isDirected:            
                A[endNode[i],startNode[i]] = 1.0   
            
    #Remove all isolated nodes
    A = A[goodIDSet,:][:,goodIDSet]

    #add self loop
    if add_self_loop:
        np.fill_diagonal(A,1.0)
    else:
        np.fill_diagonal(A,0.0)

    if plotting:
        fig,ax=plt.subplots(1,1)
        ax.matshow(A)
        plt.savefig('outputs/testadj_{0}.png'.format(watershed))
        plt.close()
    
    return A

def convertFPP2NodeIndex(comIDdict,fpplist):
    """Find the node index relative to goodIDset
    This is only used by the graph coarsening experiment
    Note: if basin not in the good comid set, it is dropped
    """
    #column order in Adj is the same as goodIDSet, 
    #so find the position of fpplist relative to goodIDSet
    #use the mapping stored in comIDdict
    fpp_node_pos=[]
    for comid in fpplist:
        if comid in comIDdict.keys(): 
            fpp_node_pos.append(comIDdict[comid])
    return fpp_node_pos

